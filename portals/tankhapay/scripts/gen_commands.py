#!/usr/bin/env python3
"""Generate the TankhaPay CLI command tree from the wired-read inventory.

Reads  captures/wired-reads.tsv  (287 true-read URLs) and the per-section splits
in captures/sections/*.tsv, and writes:
  cli/wired_manifest.go     — the single source of truth (one WiredEndpoint each)
  cli/cmd_<section>.go       — 14 section groups, each built from the manifest

Read-only by construction: only URLs present in wired-reads.tsv are emitted, and
guardrail_coverage_test.go fails the build if the manifest ever drifts from it.
"""
import os, re, sys, json, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAP = os.path.join(ROOT, "captures")
CLI = os.path.join(ROOT, "cli")

GROUPS = {
    "Dashboard": ("dashboard", "Dashboard — headline counts, alerts and wishes-data reads"),
    "Employee-Management": ("employee", "Employee master — profiles, KYC, bank, family, documents"),
    "Attendance": ("attendance", "Attendance, shifts, biometric and geo-punch reads"),
    "Leave-Management": ("leave", "Leave balances, requests, policies and holidays"),
    "Payouts": ("payouts", "Salary payouts, wallet and fund-transaction reads"),
    "Approvals": ("approvals", "Approval queues and voucher/candidate detail reads"),
    "Accounts-Taxes": ("accounts", "Wallet ledger, TDS, investment declarations and proofs"),
    "Reports": ("reports", "Compliance, liability, salary, ECR and statutory reports"),
    "Recruit-ATS": ("recruit", "Recruitment / ATS — candidates, campaigns, audiences"),
    "Masters-Config": ("masters", "Master data and configuration reads (units, designations, rates)"),
    "Org-User-Management": ("org", "Org hierarchy, geo-fencing, users, roles and access"),
    "Broadcast-Visitor-Help": ("broadcast", "Broadcasts, visitor management and help/support reads"),
    "Contract-Labour-Inventory": ("contract", "Contract-labour compliance and asset/inventory reads"),
    "Training-Performance": ("training", "Training, PMS/appraisal and performance reads"),
}

BACKENDS = [
    ("business", "https://business.tankhapay.com/api/"),
    ("mobapi", "https://mobapi.tankhapay.com/api/"),
    ("tnd", "https://tnd.tankhapay.com/api/"),
    ("tpPay", "https://mobapi.tankhapay.com/"),  # must come AFTER mobapi/api/
]


def backend_of(url):
    for key, base in BACKENDS:
        if url.startswith(base):
            return key, url[len(base):]
    return None, url


def tokens(seg):
    words = []
    for part in re.split(r"[_\-.]", seg):
        found = re.findall(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z0-9]+|[A-Z]+", part)
        words += found if found else [part]
    return [w.lower() for w in words if w]


def cmd_name(rel):
    seg = rel.split("?")[0].rstrip("/").split("/")[-1]
    tk = tokens(seg)
    while tk and tk[0] in ("get", "getall"):
        tk = tk[1:]
    while tk and tk[-1] == "api":
        tk = tk[:-1]
    if not tk:
        tk = tokens(seg)
    name = re.sub(r"[^a-z0-9-]", "", "-".join(tk)).strip("-")
    return name or "read"


def load_lines(path):
    with open(path) as f:
        return [ln.rstrip("\n") for ln in f if ln.strip()]


def main():
    # url -> section (from the per-section splits)
    url_section = {}
    for stem in GROUPS:
        p = os.path.join(CAP, "sections", stem + ".tsv")
        for ln in load_lines(p):
            url = ln.split("\t")[-1].strip()
            url_section[url] = stem

    wired = [ln.split("\t")[0].strip() for ln in load_lines(os.path.join(CAP, "wired-reads.tsv"))]

    rows = []  # (group, cmd, backend, path, url, short)
    used = collections.defaultdict(set)
    unmapped = []
    for url in wired:
        group = url_section.get(url)
        if group is None:
            unmapped.append(url)
            continue
        backend, rel = backend_of(url)
        if backend is None:
            print("!! unknown backend:", url, file=sys.stderr)
            sys.exit(2)
        base = cmd_name(rel)
        name = base
        n = 2
        while name in used[group]:
            name = f"{base}-{n}"
            n += 1
        used[group].add(name)
        rows.append((group, name, backend, rel, url, "read: " + rel))

    if unmapped:
        print(f"!! {len(unmapped)} wired URLs not found in any section split:", file=sys.stderr)
        for u in unmapped[:10]:
            print("   ", u, file=sys.stderr)
        sys.exit(2)

    rows.sort(key=lambda r: (r[0], r[1]))

    # wired_manifest.go
    out = ["package main", "",
           "// Code generated by scripts/gen_commands.py — DO NOT EDIT.",
           "// Source of truth: captures/wired-reads.tsv (the 287 true-read endpoints).", "",
           "var wiredManifest = []WiredEndpoint{"]
    for g, cmd, be, path, url, short in rows:
        out.append(
            "\t{Group: %s, Cmd: %s, Backend: %s, Path: %s, URL: %s, Short: %s},"
            % (json.dumps(g), json.dumps(cmd), json.dumps(be), json.dumps(path), json.dumps(url), json.dumps(short))
        )
    out.append("}")
    out.append("")
    with open(os.path.join(CLI, "wired_manifest.go"), "w") as f:
        f.write("\n".join(out))

    # cmd_<section>.go per group
    per = collections.Counter(r[0] for r in rows)
    for stem, (use, short) in GROUPS.items():
        count = per.get(stem, 0)
        desc = f"{short} ({count} reads)"
        body = [
            "package main", "",
            "// Code generated by scripts/gen_commands.py — DO NOT EDIT.", "",
            'import "github.com/spf13/cobra"', "",
            "func init() {",
            "\tregisterSection(func(app *App) *cobra.Command {",
            "\t\treturn buildSection(app, %s, %s, %s)" % (json.dumps(stem), json.dumps(use), json.dumps(desc)),
            "\t})",
            "}",
            "",
        ]
        fname = "cmd_" + stem.lower().replace("-", "_") + ".go"
        with open(os.path.join(CLI, fname), "w") as f:
            f.write("\n".join(body))

    print(f"generated {len(rows)} commands across {len(GROUPS)} sections")
    for stem in GROUPS:
        print(f"  {per.get(stem,0):3}  {stem}")


if __name__ == "__main__":
    main()
